Object.assign(COURSE.glossary, {
  'mcp':'Model Context Protocol. An open standard for how AI applications connect to outside tools and data.',
  'host':'The AI application the user runs (a chat app, an IDE). It creates clients, asks the user for consent, and talks to the language model.',
  'client':'The part of the host that holds exactly one connection to one MCP server.',
  'server':'A program that offers tools, resources and prompts over MCP. It can run on your machine or on the internet.',
  'tool':'A function the server lets the model call, like get_weather. Model-controlled.',
  'resource':'Data the server exposes by URI, like a file. Application-controlled.',
  'prompt':'A reusable message template the server offers, usually shown as a slash command. User-controlled.',
  'json-rpc':'JSON-RPC 2.0, the small message format MCP uses: requests, results, errors and notifications.',
  'request':'A message that expects an answer. It has an id and a method.',
  'response':'The answer to a request, with the same id. Either a result or an error.',
  'notification':'A one-way message with no id. Nobody replies to it.',
  'capability':'A feature one side declares it supports, like tools or elicitation. Neither side may use a feature the other did not declare.',
  '_meta':'A reserved object on params and results for metadata. In 2026-07-28 every request carries the protocol version and client capabilities here.',
  'protocol version':'A date string such as 2026-07-28. It is the last date a backwards-incompatible change was made.',
  'server/discover':'A request every modern server must answer. It returns supported versions, capabilities, instructions and server info.',
  'stateless':'Each request carries everything needed to understand it. The server must not rely on earlier requests on the same connection.',
  'handle':'An explicit ID, minted by the server, that refers to state across requests (for example a basket_id).',
  'transport':'How messages physically travel: stdio, Streamable HTTP, or a custom binding.',
  'stdio':'Transport where the client starts the server as a child process and they exchange one JSON message per line on stdin/stdout.',
  'streamable http':'Transport where every message is a POST to one endpoint; the answer comes back as JSON or as an SSE stream.',
  'sse':'Server-Sent Events: a way for an HTTP response to stream several messages.',
  'mrtr':'Multi Round-Trip Request. The server answers with input_required, the client gathers the input, then retries the same request with the answers.',
  'inputrequiredresult':'A result with resultType "input_required" that asks the client for input (elicitation, sampling or roots) before the request can finish.',
  'requeststate':'An opaque string the server gives back in an input_required result. The client must echo it unchanged on the retry. Treat it as attacker-controlled.',
  'elicitation':'Asking the user for information mid-request, either with a small form or by sending them to a URL.',
  'sampling':'Deprecated. A server asking the client’s language model to generate text.',
  'roots':'Deprecated. File-system roots the client tells the server about.',
  'subscription':'A long-lived subscriptions/listen request on which the server sends change notifications.',
  'progress token':'A value the client puts in _meta.progressToken so the server can send progress notifications for that request.',
  'cursor':'An opaque string for fetching the next page of a list.',
  'ttlms':'How many milliseconds a cacheable result stays fresh.',
  'cachescope':'"public" (shareable across users) or "private" (only the same authorization context).',
  'extension':'An optional, opt-in add-on to the protocol, named like io.modelcontextprotocol/tasks.',
  'task':'From the Tasks extension: a long-running tools/call the client polls with tasks/get.',
  'oauth':'OAuth 2.1, the standard used to authorize MCP clients over HTTP.',
  'resource server':'In OAuth terms, the MCP server: it accepts and checks access tokens.',
  'authorization server':'The server that signs the user in and issues access tokens.',
  'prm':'Protected Resource Metadata (RFC 9728): a JSON document that tells clients which authorization server protects this MCP server.',
  'cimd':'Client ID Metadata Document: the client’s ID is an HTTPS URL pointing to a JSON document describing it. The recommended way to register.',
  'dcr':'Dynamic Client Registration (RFC 7591). Deprecated in 2026-07-28 in favour of CIMD.',
  'pkce':'Proof Key for Code Exchange. A random secret proves that the app finishing the login is the one that started it. Required in MCP.',
  'resource indicator':'The resource parameter (RFC 8707) naming exactly which MCP server a token is for.',
  'audience':'Who a token is meant for. An MCP server must reject tokens whose audience is not itself.',
  'scope':'A named permission a token carries, like files:read.',
  'issuer':'The identifier of an authorization server. Clients check it (RFC 9207) to avoid mix-up attacks.',
  'token passthrough':'Forwarding a token the server received to another service. Forbidden in MCP.',
  'confused deputy':'An attack where a trusted middleman is tricked into using its own authority for an attacker.',
  'ssrf':'Server-Side Request Forgery: tricking a server into fetching an internal URL.',
  'tool poisoning':'Hiding malicious instructions in a tool’s description or changing a tool after the user approved it.',
  'prompt injection':'Text in data (a web page, a file) that tries to give the model new instructions.',
  'legacy':'MCP versions 2025-11-25 and earlier, which use the initialize handshake.',
  'modern':'MCP versions 2026-07-28 and later: stateless, no handshake.',
  'dual-era':'An implementation that supports both legacy and modern peers.',
  'inputschema':'The JSON Schema (2020-12 by default) describing a tool’s arguments.',
  'outputschema':'An optional JSON Schema describing a tool’s structuredContent.',
  'structuredcontent':'A tool result’s machine-readable JSON value, next to its human-readable content blocks.',
  'annotations':'Hints such as readOnlyHint on tools, or audience/priority on content. Untrusted unless the server is trusted.',
  'x-mcp-header':'A marker in a tool’s inputSchema that copies one argument into an Mcp-Param-* HTTP header.',
  'origin header':'The browser’s Origin header. HTTP servers must validate it to stop DNS rebinding attacks.',
  'dns rebinding':'An attack where a web page makes your browser talk to a server on your own machine.',
  'resulttype':'Required on every result: "complete" for a final result, "input_required" to ask for input. Extensions may add values such as "task".',
});

